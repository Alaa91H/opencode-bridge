"""Probe and apply the systemd hardening directives a host can actually support.

The release unit requests the full hardening set. Some container managers run an
unprivileged user manager whose ``CapEff`` set is empty: systemd can no longer
drop capabilities, so a unit containing ``ProtectClock``/``ProtectKernelLogs``/
``ProtectKernelModules`` fails with status 218/CAPABILITIES before the bridge
starts. Hard-coding a weaker unit would weaken every host, so deployment probes
the real host and writes a generated drop-in only for the directives it cannot
apply.

``NoNewPrivileges=yes`` is deliberately kept in the unit and is never disabled
by the generated drop-in.
"""

from __future__ import annotations

import argparse
import json
import os
import shutil
import subprocess
import sys
from collections.abc import Callable, Iterable, Sequence
from pathlib import Path

# Ordered so an incremental probe is deterministic and logs are stable.
HARDENING_PROPERTIES: tuple[str, ...] = (
    "ProtectClock",
    "ProtectHostname",
    "ProtectKernelLogs",
    "ProtectKernelModules",
    "ProtectKernelTunables",
    "RestrictRealtime",
    "RestrictSUIDSGID",
    "LockPersonality",
)
COMPAT_DROPIN_NAME = "20-hardening-compat.conf"
PROBE_TIMEOUT_SECONDS = 20.0

Probe = Callable[[tuple[str, ...]], bool]


def _systemd_run() -> str | None:
    return shutil.which("systemd-run")


def probe_properties(properties: Sequence[str], *, timeout: float = PROBE_TIMEOUT_SECONDS) -> bool:
    """Return whether a transient user service starts with these directives."""

    binary = _systemd_run()
    if binary is None:
        return False
    argv = [
        binary,
        "--user",
        "--quiet",
        "--wait",
        "--collect",
        "--service-type=oneshot",
        "--property=NoNewPrivileges=yes",
    ]
    argv.extend(f"--property={name}=yes" for name in properties)
    argv.append("/bin/true")
    try:
        result = subprocess.run(  # noqa: S603 - fixed argv built from the allow-list above.
            argv,
            text=True,
            capture_output=True,
            timeout=timeout,
            check=False,
        )
    except (OSError, subprocess.TimeoutExpired):
        return False
    return result.returncode == 0


def supported_properties(probe: Probe | None = None) -> tuple[str, ...]:
    """Find the largest ordered subset of optional directives that starts.

    Each candidate is tested with the directives accepted so far. This catches
    both a directive that is unsupported on its own and one that only fails in
    combination with an earlier directive. A probe that cannot run at all
    yields an empty optional set; the unit's ``NoNewPrivileges=yes`` remains.
    """

    run = probe or probe_properties
    if not run(()):
        return ()

    accepted: list[str] = []
    for name in HARDENING_PROPERTIES:
        candidate = (*accepted, name)
        if run(candidate):
            accepted.append(name)
    return tuple(accepted)


def disabled_properties(supported: Iterable[str]) -> tuple[str, ...]:
    enabled = set(supported)
    return tuple(name for name in HARDENING_PROPERTIES if name not in enabled)


def dropin_text(disabled: Iterable[str]) -> str:
    names = tuple(disabled)
    lines = [
        "# Generated by systemd.py after probing this host's systemd capabilities.",
        "# Do not edit. The generated draft is replaced on the next deployment.",
        "# NoNewPrivileges=yes remains enabled in the release unit.",
        "[Service]",
    ]
    lines.extend(f"{name}=no" for name in names)
    return "\n".join(lines) + "\n"


def install_compat_dropin(
    dropin_dir: Path | str,
    supported: Iterable[str] | None = None,
    *,
    probe: Probe | None = None,
) -> tuple[str, ...]:
    """Write or remove the generated compatibility drop-in.

    Returns the directives that were disabled. A full-capability host gets no
    generated file; a previously generated fallback is removed so support can
    never become permanently global.
    """

    if supported is None:
        supported = supported_properties(probe)
    disabled = disabled_properties(supported)
    directory = Path(dropin_dir)
    target = directory / COMPAT_DROPIN_NAME
    if not disabled:
        target.unlink(missing_ok=True)
        return ()
    directory.mkdir(parents=True, exist_ok=True)
    temporary = target.with_suffix(".tmp")
    temporary.write_text(dropin_text(disabled), encoding="utf-8")
    os.chmod(temporary, 0o644)
    temporary.replace(target)
    return disabled


def self_check(probe: Probe | None = None) -> dict[str, object]:
    supported = supported_properties(probe)
    return {
        "supported": list(supported),
        "disabled": list(disabled_properties(supported)),
        "no_new_privileges": "yes",
        "compat_dropin": COMPAT_DROPIN_NAME,
    }


def main(argv: Sequence[str] | None = None) -> int:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument(
        "--dropin-dir",
        type=Path,
        help="directory in which to write/remove the generated compatibility drop-in",
    )
    parser.add_argument("--self-check", action="store_true", help="print the probe result without writing files")
    arguments = parser.parse_args(argv)
    if arguments.self_check:
        sys.stdout.write(json.dumps(self_check(), indent=2, sort_keys=True) + "\n")
        return 0
    if arguments.dropin_dir is None:
        parser.error("--dropin-dir is required unless --self-check is used")
    disabled = install_compat_dropin(arguments.dropin_dir)
    sys.stdout.write(
        json.dumps(
            {"dropin_dir": str(arguments.dropin_dir), "disabled": list(disabled)},
            indent=2,
            sort_keys=True,
        )
        + "\n"
    )
    return 0


if __name__ == "__main__":
    sys.exit(main())
